def create_db(db_path):
    conn = sqlite3.connect(db_path)
    conn.executescript(SCHEMA)
    return conn


def seed_db(conn):
    cur = conn.execute("SELECT COUNT(*) FROM texts")
    if cur.fetchone()[0] > 0:
        print("Database already contains data; skipping seed.")
        return
    conn.executemany(
        "INSERT INTO texts (text, author, work, country, region, tradition,"
        " language, era, source) VALUES (?,?,?,?,?,?,?,?,?)",
        SEED,
    )
    conn.commit()
    print(f"Seeded {len(SEED)} entries.")


def import_csv(conn, csv_path):
    with open(csv_path, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        rows = [
            (
                r.get("text", "").strip(),
                r.get("author", "").strip(),
                r.get("work", "").strip(),
                r.get("country", "").strip(),
                r.get("region", "").strip(),
                r.get("tradition", "").strip(),
                r.get("language", "").strip(),
                r.get("era", "").strip(),
                r.get("source", "").strip(),
            )
            for r in reader
            if r.get("text", "").strip() and r.get("country", "").strip()
        ]
    if not rows:
        print("No valid rows found. Required columns: text, country.")
        return
    conn.executemany(
        "INSERT INTO texts (text, author, work, country, region, tradition,"
        " language, era, source) VALUES (?,?,?,?,?,?,?,?,?)",
        rows,
    )
    conn.commit()
    print(f"Imported {len(rows)} rows from {csv_path}.")


def print_stats(conn):
    total = conn.execute("SELECT COUNT(*) FROM texts").fetchone()[0]
    countries = conn.execute(
        "SELECT COUNT(DISTINCT country) FROM texts").fetchone()[0]
    languages = conn.execute(
        "SELECT COUNT(DISTINCT language) FROM texts").fetchone()[0]
    traditions = conn.execute(
        "SELECT COUNT(DISTINCT tradition) FROM texts").fetchone()[0]
    print(f"Texts:      {total}")
    print(f"Countries:  {countries}")
    print(f"Languages:  {languages}")
    print(f"Traditions: {traditions}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--import", dest="csv_path", metavar="CSV",
                        help="Import your own corpus CSV into the database.")
    parser.add_argument("--stats", action="store_true",
                        help="Print corpus statistics.")
    args = parser.parse_args()

    conn = create_db(DB_PATH)

    if args.csv_path:
        import_csv(conn, args.csv_path)
    else:
        seed_db(conn)

    if args.stats or not args.csv_path:
        print_stats(conn)

    conn.close()


if __name__ == "__main__":
    main()
